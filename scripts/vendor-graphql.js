'use strict';

// Writes src/renderer/vendor/graphql.min.js: graphql-js and the CodeMirror 5 GraphQL addons
// (codemirror-graphql: mode, autocomplete, linting and hover info for queries and variables), as
// one script for the window. It uses the CodeMirror the page already loads, and exposes graphql-js
// as window.HDGraphQL. Run `npm run vendor` after upgrading graphql or codemirror-graphql.
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const entry = `
  require('codemirror-graphql/mode');
  require('codemirror-graphql/hint');
  require('codemirror-graphql/lint');
  require('codemirror-graphql/info');
  require('codemirror-graphql/variables/mode');
  require('codemirror-graphql/variables/hint');
  require('codemirror-graphql/variables/lint');
  window.HDGraphQL = require('graphql');
`;

// "codemirror" is the page's own; its addons (show-hint, lint) are loaded by index.html.
const pageCodeMirror = {
  name: 'page-codemirror',
  setup(build) {
    build.onResolve({ filter: /^codemirror(\/.*)?$/ }, (args) => ({ path: args.path, namespace: 'page-codemirror' }));
    build.onLoad({ filter: /.*/, namespace: 'page-codemirror' }, (args) => ({
      contents: args.path === 'codemirror' ? 'module.exports = window.CodeMirror;' : '',
      loader: 'js',
    }));
  },
};

const versions = ['graphql', 'codemirror-graphql', 'graphql-language-service'].map((p) => `${p} ${require(`${p}/package.json`).version}`).join(', ');
const out = path.join(__dirname, '..', 'src', 'renderer', 'vendor', 'graphql.min.js');
fs.mkdirSync(path.dirname(out), { recursive: true });
esbuild.build({
  stdin: { contents: entry, resolveDir: path.join(__dirname, '..'), loader: 'js' },
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  platform: 'browser',
  // One copy of graphql-js: its CommonJS build everywhere, or schema checks fail across copies.
  mainFields: ['main'],
  conditions: ['require'],
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none',
  plugins: [pageCodeMirror],
  banner: { js: `/*! ${versions} (MIT License). Generated by scripts/vendor-graphql.js; do not edit. */` },
  outfile: out,
}).then(() => {
  console.log(`Wrote ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1024).toFixed(0)} KB) from ${versions}`);
}, (e) => { console.error(e.message); process.exit(1); });
